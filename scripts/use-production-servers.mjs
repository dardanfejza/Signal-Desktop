// Fork helper: make `pnpm start` (NODE_ENV=development) talk to Signal's
// PRODUCTION servers instead of staging, so the dev instance can be linked to
// a real phone. Writes config/local-development.json (gitignored), which the
// `config` package layers over development.json. The storage profile stays
// `development`, so data lives in Signal-development, never in the installed
// client's profile. Pass --staging to remove the override again.

import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'config', 'local-development.json');

if (process.argv.includes('--staging')) {
  if (existsSync(target)) {
    unlinkSync(target);
  }
  console.log(
    'removed config/local-development.json — dev build is back on staging'
  );
  process.exit(0);
}

const production = JSON.parse(
  readFileSync(join(root, 'config', 'production.json'), 'utf8')
);

// Only the server-side endpoints and keys; never the updater or billing bits.
const KEYS = [
  'serverUrl',
  'storageUrl',
  'cdn',
  'sfuUrl',
  'challengeUrl',
  'registrationChallengeUrl',
  'serverPublicParams',
  'serverTrustRoots',
  'genericServerPublicParams',
  'backupServerPublicParams',
];

const override = {
  _comment: 'generated by scripts/use-production-servers.mjs',
};
for (const key of KEYS) {
  if (!(key in production)) {
    throw new Error(`config/production.json has no "${key}"`);
  }
  override[key] = production[key];
}

writeFileSync(target, `${JSON.stringify(override, null, 2)}\n`);
console.log(
  'wrote config/local-development.json — `pnpm start` now uses chat.signal.org (profile: Signal-development)'
);
